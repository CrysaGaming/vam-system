// ─────────────────────────────────────────────────────────────────────
// Helpers
// ─────────────────────────────────────────────────────────────────────

function severityColor(s: SuggestionSeverity): string {
  return s === 'warning' ? COLORS.amber : COLORS.blue;
}

function severityGlyph(s: SuggestionSeverity): string {
  return s === 'warning' ? '!' : 'i';
}

function smoothnessColor(score: number): string {
  if (score >= 85) return COLORS.green;
  if (score >= 70) return COLORS.green;
  if (score >= 55) return COLORS.amber;
  if (score >= 40) return COLORS.amber;
  return COLORS.red;
}

function smoothnessLabel(score: number): string {
  if (score >= 85) return 'excellent';
  if (score >= 70) return 'good';
  if (score >= 55) return 'acceptable';
  if (score >= 40) return 'needs work';
  return 'rough';
}

function formatFlightTime(min: number | null): string {
  if (min === null) return '—';
  const h = Math.floor(min / 60);
  const m = min % 60;
  if (h > 0) return `${h}h ${m}m`;
  return `${m}m`;
}

// ─────────────────────────────────────────────────────────────────────
// Document
// ─────────────────────────────────────────────────────────────────────

export function PirepLogbookPdf({ data }: { data: LogbookData }) {
  const {
    pirep,
    airline,
    route,
    departure,
    arrival,
    pilot,
    aircraft,
    approach,
    landing,
    smoothnessScore,
    suggestions,
  } = data;

  // Touchdown-VSI severity helpers — same logic as detail-page Landing
  // section but inline (no shared helper, klein genug).
  const tdVsi =
    landing?.verticalFpmAtTouchdown !== null &&
    landing?.verticalFpmAtTouchdown !== undefined
      ? Math.abs(landing.verticalFpmAtTouchdown)
      : null;
  const tdSeverity =
    tdVsi === null
      ? '—'
      : tdVsi < 200
        ? 'smooth'
        : tdVsi < 400
          ? 'normal'
          : tdVsi < 600
            ? 'firm'
            : tdVsi < 1000
              ? 'hard'
              : 'severe';

  return (
    <Document
      title={`Logbook ${route.flightNumber ?? 'PIREP'} ${departure.icao}-${arrival.icao}`}
      author={airline.name}
      subject="PIREP Logbook"
      creator="VAM-System"
    >
      <Page size="A4" style={styles.page}>
        {/* ───── Header ───── */}
        <View style={styles.header}>
          <View style={styles.headerLeft}>
            <Text style={styles.airlineName}>{airline.name}</Text>
            <Text style={styles.headerSubtitle}>
              {airline.icao ? `${airline.icao} · ` : ''}Pilot Logbook
            </Text>
          </View>
          <View style={styles.headerRight}>
            <Text style={styles.flightNumber}>
              {route.flightNumber ?? 'PIREP'}
            </Text>
            <Text style={styles.pirepDate}>
              {pirep.submittedAt.toLocaleString('de-DE', {
                dateStyle: 'long',
                timeStyle: 'short',
              })}
            </Text>
            <Text style={styles.pirepDate}>Status: {pirep.status}</Text>
          </View>
        </View>

        {/* ───── Route strip ───── */}
        <View style={styles.routeStrip}>
          <View style={styles.routeAirport}>
            <Text style={styles.routeIcao}>{departure.icao}</Text>
            <Text style={styles.routeAirportName}>
              {departure.name}
              {departure.city ? `\n${departure.city}` : ''}
            </Text>
          </View>
          <View style={styles.routeArrow}>
            <Text style={styles.routeArrowGlyph}>→</Text>
            <Text style={styles.routeDistance}>
              {route.distanceNm !== null ? `${route.distanceNm} nm` : '— nm'}
            </Text>
          </View>
          <View style={styles.routeAirport}>
            <Text style={styles.routeIcao}>{arrival.icao}</Text>
            <Text style={styles.routeAirportName}>
              {arrival.name}
              {arrival.city ? `\n${arrival.city}` : ''}
            </Text>
          </View>
        </View>

        {/* ───── KPI grid: Block-Time, Fuel, Pax, Smoothness ───── */}
        <View style={styles.kpiGrid}>
          <View style={styles.kpiCard}>
            <Text style={styles.kpiLabel}>Block-Time</Text>
            <Text style={styles.kpiValue}>
              {formatFlightTime(pirep.flightTimeMin)}
            </Text>
          </View>
          <View style={styles.kpiCard}>
            <Text style={styles.kpiLabel}>Treibstoff</Text>
            <Text style={styles.kpiValue}>
              {pirep.fuelUsedKg !== null ? `${pirep.fuelUsedKg}` : '—'}
              {pirep.fuelUsedKg !== null && (
                <Text style={styles.kpiUnit}> kg</Text>
              )}
            </Text>
          </View>
          <View style={styles.kpiCard}>
            <Text style={styles.kpiLabel}>Passagiere</Text>
            <Text style={styles.kpiValue}>
              {pirep.passengerCount !== null ? pirep.passengerCount : '—'}
            </Text>
            {pirep.cargoKg !== null && pirep.cargoKg > 0 && (
              <Text style={styles.kpiSub}>+{pirep.cargoKg} kg Cargo</Text>
            )}
          </View>
          <View
            style={[
              styles.kpiCard,
              smoothnessScore !== null
                ? { borderColor: smoothnessColor(smoothnessScore) }
                : {},
            ]}
          >
            <Text style={styles.kpiLabel}>Smoothness</Text>
            {smoothnessScore !== null ? (
              <>
                <Text
                  style={[
                    styles.kpiValue,
                    { color: smoothnessColor(smoothnessScore) },
                  ]}
                >
                  {smoothnessScore}
                  <Text style={styles.kpiUnit}> /100</Text>
                </Text>
                <Text style={styles.kpiSub}>
                  {smoothnessLabel(smoothnessScore)}
                </Text>
              </>
            ) : (
              <>
                <Text style={[styles.kpiValue, { color: COLORS.faint }]}>—</Text>
                <Text style={styles.kpiSub}>keine ACARS-daten</Text>
              </>
            )}
          </View>
        </View>

        {/* ───── Pilot + Aircraft ───── */}
        <View style={styles.twoCol}>
          <View style={styles.sectionCard}>
            <Text style={styles.sectionLabel}>Pilot</Text>
            <Text style={styles.sectionValue}>
              {pilot.name ?? 'Unbenannt'}
            </Text>
            <Text style={styles.sectionSub}>
              {pilot.rankName ?? 'Kein Rang'}
            </Text>
          </View>
          <View style={styles.sectionCard}>
            <Text style={styles.sectionLabel}>Aircraft</Text>
            {aircraft ? (
              <>
                <Text style={[styles.sectionValue, { fontFamily: 'Courier-Bold' }]}>
                  {aircraft.registration}
                </Text>
                <Text style={styles.sectionSub}>{aircraft.type}</Text>
              </>
            ) : (
              <Text style={styles.sectionValue}>—</Text>
            )}
          </View>
        </View>

        {/* ───── Approach metrics (wenn data) ───── */}
        {approach &&
          (approach.iasAt1000ft !== null ||
            approach.glideslopeQualityPercent !== null ||
            approach.stabilizationScorePercent !== null) && (
            <View style={styles.threeCol}>
              <View style={styles.sectionCard}>
                <Text style={styles.sectionLabel}>IAS @ 1000ft AGL</Text>
                <Text style={styles.sectionValue}>
                  {approach.iasAt1000ft !== null
                    ? `${approach.iasAt1000ft} kt`
                    : '—'}
                </Text>
              </View>
              <View style={styles.sectionCard}>
                <Text style={styles.sectionLabel}>Glideslope (3°)</Text>
                <Text style={styles.sectionValue}>
                  {approach.glideslopeQualityPercent !== null
                    ? `${approach.glideslopeQualityPercent.toFixed(0)}%`
                    : '—'}
                </Text>
              </View>
              <View style={styles.sectionCard}>
                <Text style={styles.sectionLabel}>Stabilized</Text>
                <Text style={styles.sectionValue}>
                  {approach.stabilizationScorePercent !== null
                    ? `${approach.stabilizationScorePercent.toFixed(0)}%`
                    : '—'}
                </Text>
              </View>
            </View>
          )}

        {/* ───── Landing metrics (wenn data) ───── */}
        {landing && landing.verticalFpmAtTouchdown !== null && (
          <View style={styles.threeCol}>
            <View style={styles.sectionCard}>
              <Text style={styles.sectionLabel}>Touchdown-Rate</Text>
              <Text style={styles.sectionValue}>
                {tdVsi !== null ? `${tdVsi} fpm` : '—'}
              </Text>
              <Text style={styles.sectionSub}>{tdSeverity}</Text>
            </View>
            <View style={styles.sectionCard}>
              <Text style={styles.sectionLabel}>Groundspeed</Text>
              <Text style={styles.sectionValue}>
                {landing.groundSpeedKtsAtTouchdown !== null
                  ? `${landing.groundSpeedKtsAtTouchdown} kt`
                  : '—'}
              </Text>
              {landing.altitudeAglAtTouchdown !== null && (
                <Text style={styles.sectionSub}>
                  @ {landing.altitudeAglAtTouchdown}ft AGL
                </Text>
              )}
            </View>
            <View style={styles.sectionCard}>
              <Text style={styles.sectionLabel}>Touchdown @</Text>
              <Text style={[styles.sectionValue, { fontFamily: 'Courier-Bold' }]}>
                {landing.atIcao ?? '—'}
              </Text>
              {landing.atIcao && landing.atIcao !== arrival.icao && (
                <Text style={[styles.sectionSub, { color: COLORS.amber }]}>
                  ≠ Arrival ({arrival.icao})
                </Text>
              )}
            </View>
          </View>
        )}

        {/* ───── Suggestions ───── */}
        {suggestions.length > 0 && (
          <View style={styles.suggestionBox}>
            <Text style={styles.suggestionTitle}>
              Verbesserungshinweise ({suggestions.length})
            </Text>
            {suggestions.map((s, idx) => (
              <View key={idx} style={styles.suggestionItem}>
                <Text
                  style={[
                    styles.suggestionBullet,
                    { color: severityColor(s.severity) },
                  ]}
                >
                  {severityGlyph(s.severity)}
                </Text>
                <View style={styles.suggestionBody}>
                  <Text style={styles.suggestionTitleText}>{s.title}</Text>
                  {s.detail && (
                    <Text style={styles.suggestionDetail}>{s.detail}</Text>
                  )}
                </View>
              </View>
            ))}
          </View>
        )}

        {/* ───── Remarks ───── */}
        {pirep.remarks && pirep.remarks.trim().length > 0 && (
          <View style={styles.remarksBox}>
            <Text style={styles.sectionLabel}>Bemerkungen</Text>
            <Text style={styles.remarksText}>{pirep.remarks}</Text>
          </View>
        )}

        {/* ───── Footer ───── */}
        <View style={styles.footer}>
          <Text>VAM-System · Pilot Logbook · PIREP {pirep.id}</Text>
          <Text>
            Generated{' '}
            {new Date().toLocaleString('de-DE', {
              dateStyle: 'short',
              timeStyle: 'short',
            })}
          </Text>
        </View>
      </Page>
    </Document>
  );
}
