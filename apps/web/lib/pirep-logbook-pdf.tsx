/**
 * Track 5 #5 — PIREP-Logbook PDF document.
 *
 * Single-page A4 debrief-sheet das alle wichtigen flight-metrics
 * eines PIREPs in print-ready form rendert. Renderable serverside
 * via @react-pdf/renderer.renderToStream().
 *
 * # Why a PDF (and not screenshot or HTML-print)
 *
 * - Pilots wollen ein "echtes" logbook-document zum archivieren —
 *   nicht eine HTML-page die je nach browser anders aussieht
 * - Konstantes A4-layout, vorhersagbare seitenränder
 * - Email-fähig, druckbar, embed-bar in flight-portfolios
 * - Print-style-rules in HTML sind brittle (jeder browser interpretiert
 *   sie anders); @react-pdf/renderer gibt deterministischen output
 *
 * # Layout (top to bottom)
 *
 * 1. Header-band: Airline-name + PIREP-id + flight-number + date
 * 2. Route-strip: ICAO → ICAO mit airport-namen darunter
 * 3. Hero-KPIs (4-col grid): Block-time, Distance, Fuel, Smoothness
 * 4. Pilot + Aircraft (2-col)
 * 5. Approach + Landing metrics (3-col grid wenn data available)
 * 6. Auto-Suggestions (wenn vorhanden) — bullet-list, color-coded
 * 7. Footer: "generated by VAM-System" + ISO-timestamp
 *
 * NICHT included (V1 cutoff):
 * - Map/trail-visualization (würde clientside-screenshot oder static-map-API brauchen)
 * - Charts (vertical-profile, IAS/VSI) — recharts läuft nicht in @react-pdf
 * - Annotations (Track 5 #3) — könnte als appendix-page; V1 single-page
 *
 * # Font-strategy
 *
 * Standard PDF fonts ohne external-font-fetches: Helvetica (sans-serif)
 * für body, Courier (mono) für ICAO/registrations/numeric data. Beide
 * sind PDF-base-14 fonts, kein download nötig, kein bundling-overhead.
 * (Vermeidet das @react-pdf font-registration drama mit unicode-ranges
 * und woff-fetches die in serverless-environments oft fail'n.)
 */

